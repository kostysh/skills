import subprocess,re,json
from pathlib import Path
root=Path('/tmp/ui-rev-20260908/results-candidate-spa')
def run(*args):
 p=subprocess.run(['bash',str(root/'browser.sh'),*args],capture_output=True,text=True)
 print(p.stdout,flush=True)
 if p.returncode: raise RuntimeError(args)
 return p.stdout
def ref(s,label):
 return '@'+re.search(label+r'[^\n]*\[ref=(e\d+)\]',s).group(1)
run('open','http://127.0.0.1:43786')
s=run('snapshot')
run('click',ref(s,'link "Alpha"'))
run('wait','--text','Request 1')
s=run('snapshot')
run('fill',ref(s,'textbox "Name"'),'Alpha failed draft')
run('click',ref(s,'button "Save"'))
run('wait','--text','Try again: temporary save error')
s=run('snapshot')
assert 'Alpha failed draft' in run('get','value',ref(s,'textbox "Name"'))
run('fill',ref(s,'textbox "Name"'),'Alpha corrected saved')
run('click',ref(s,'button "Save"'))
run('wait','--text','Saved')
s=run('snapshot')
assert 'Alpha corrected saved' in run('get','value',ref(s,'textbox "Name"'))
run('click',ref(s,'link "Back to requests"'))
run('wait','--text','Alpha corrected saved')
s=run('snapshot')
run('click',ref(s,'link "Alpha corrected saved"'))
run('wait','--text','Request 1')
s=run('snapshot')
assert 'Alpha corrected saved' in run('get','value',ref(s,'textbox "Name"'))
run('reload')
run('wait','--text','Request 1')
s=run('snapshot')
assert 'Alpha corrected saved' in run('get','value',ref(s,'textbox "Name"'))
assert '/items/1' in run('get','url')
run('network','requests')
run('network','har','stop',str(root/'requests.har'))
run('close')
(root/'actual-result.txt').write_text('completed: first PATCH error retained Alpha failed draft; corrected retry saved Alpha corrected saved; list, detail return, reload all matched; route /items/1. Local synthetic HTTP only.\n')
